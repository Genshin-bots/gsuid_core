def test_gold_sentences_match_labels() -> None:
    """整组句式都判对。失败时列出原标签、判成的标签和原因。"""
    wrong: list[str] = []
    counts = {"闲聊": 0, "工具": 0, "问答": 0}
    for label, text in _GOLD:
        counts[label] = counts[label] + 1
        hit = classify_sentence(text)
        if hit["intent"] != label:
            wrong.append(f"{label}->{hit['intent']} {text} ({hit['reason']})")
    assert counts["闲聊"] >= 60
    assert counts["工具"] >= 50
    assert counts["问答"] >= 30
    assert wrong == []


def test_classify_is_faster_than_sklearn_baseline() -> None:
    """旧模型同一组测得 2.44ms/句。这里的上限是 0.2ms/句。"""
    for _ in range(3):
        for _, text in _GOLD:
            classify_sentence(text)
    started = time.perf_counter()
    repeats = 20
    for _ in range(repeats):
        for _, text in _GOLD:
            classify_sentence(text)
    per_ms = (time.perf_counter() - started) / (repeats * len(_GOLD)) * 1000
    assert per_ms < 0.2


def test_ellipsis_after_tools_becomes_tool() -> None:
    hit = asyncio.run(
        classifier_service.predict_async(
            "然后呢",
            prior_user_turns=["查一下面板"],
            prev_turn_used_tools=True,
        )
    )
    assert hit["intent"] == "工具"


