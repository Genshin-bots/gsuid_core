def test_import_skips_sklearn_and_stays_under_40mb() -> None:
    """旧分类器导入工作集 +244MB，并且带上 sklearn 与 jieba。"""
    script = textwrap.dedent(
        """
        import gc
        import psutil
        proc = psutil.Process()
        gc.collect()
        before = proc.memory_info().rss
        from gsuid_core.ai_core.classifier.mode_classifier import classify_sentence
        classify_sentence("你好")
        gc.collect()
        after = proc.memory_info().rss
        import sys
        print(round((after - before) / 1048576, 1))
        print("sklearn" in sys.modules)
        print("jieba" in sys.modules)
        """
    )
    completed = subprocess.run(
        [sys.executable, "-c", script],
        check=True,
        capture_output=True,
        text=True,
    )
    lines = [line for line in completed.stdout.splitlines() if line]
    assert len(lines) >= 3
    delta_mb = float(lines[-3])
    assert delta_mb < 40
    assert lines[-2] == "False"
    assert lines[-1] == "False"
